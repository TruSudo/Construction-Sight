'use strict';
const {chromium}=require('../visual/node_modules/playwright');
const {spawnSync}=require('child_process');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const page=await browser.newPage({viewport:{width:1672,height:941}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const base=process.argv[2],directory=process.argv[3];
  await page.goto(base);await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  const inventory=await page.evaluate(()=>fetch('/api/investigations').then(r=>r.json()));
  if(inventory.total!==2)throw Error('Review fixture must contain two retained investigations');
  const identity=inventory.rows[0].investigation_id;
  const dossier=await page.evaluate(id=>fetch('/api/investigations/'+encodeURIComponent(id)).then(r=>r.json()),identity);
  const relationship=dossier.candidate_source_links[0].relationship_id;
  const preview=await page.evaluate(id=>fetch('/api/investigation-review?relationship='+encodeURIComponent(id)).then(r=>r.json()),relationship);
  await page.click('nav button[data-page="Project Intelligence"]');
  await page.waitForSelector('[data-investigation-id]');
  async function openDossier(){await page.evaluate(id=>openInvestigationDossier(id),identity);await page.waitForSelector('[data-association-review]');}
  await openDossier();
  // A late preview must not replace a dialog the operator opened afterwards.
  let held,signal;const intercepted=new Promise(resolve=>{signal=resolve;});
  await page.route('**/api/investigation-review?*',route=>{held=route;signal();});
  await page.locator('[data-association-review]').first().click();
  await intercepted;
  await page.waitForFunction(()=>document.querySelector('#action-content').textContent.includes('Loading the current candidate'));
  await page.click('#action-close');await page.click('#workspace-menu');
  await page.waitForSelector('#settings-form');
  if(!held)throw Error('Preview request was not intercepted');
  const finished=page.waitForEvent('requestfinished',{predicate:request=>request.url().includes('/api/investigation-review?')});
  await held.fulfill({status:200,contentType:'application/json',body:JSON.stringify(preview)});
  await finished;
  await page.unroute('**/api/investigation-review?*');
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)));
  if(await page.locator('#association-review-form').count())throw Error('Late preview replaced settings');
  await page.click('#action-close');
  await openDossier();await page.locator('[data-association-review]').first().click();
  await page.waitForSelector('#association-review-form');
  if(!(await page.locator('#action-content').textContent()).includes('does not verify project identity'))throw Error('Review limitations missing');
  const displayed=await page.locator('[data-review-evidence]').allTextContents();
  if(displayed.length!==2||displayed.some(text=>{const detail=JSON.parse(text);return !detail.sources?.length||!detail.evidence?.length||detail.evidence.some(record=>!record.content_hash);}))throw Error('Retained claims or hashed evidence missing from review');
  await page.selectOption('#association-review-form [name=decision]','associate');
  const target=preview.target_choices[0];
  await page.selectOption('#association-review-form [name=target]',target);
  await page.fill('#association-review-form [name=reviewer]','Offline browser reviewer');
  await page.fill('#association-review-form [name=reason]','Reviewed both synthetic source records as context.');
  let writes=0;page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/api/investigation-review'))writes++;});
  await page.click('#association-review-form button[type=submit]');
  if(writes)throw Error('Unchecked review confirmation submitted a mutation');
  await page.check('#association-review-form [name=confirmed]');
  require('fs').mkdirSync('tests/visual/output',{recursive:true});
  const layout=await page.locator('#action-dialog').evaluate(dialog=>({left:dialog.getBoundingClientRect().left,right:dialog.getBoundingClientRect().right,width:innerWidth,overflow:document.querySelector('#action-content').scrollWidth-document.querySelector('#action-content').clientWidth}));
  if(layout.left<0||layout.right>layout.width||layout.overflow>1)throw Error('Review dialog overflows the approved viewport: '+JSON.stringify(layout));
  await page.screenshot({path:'tests/visual/output/association-review.png'});
  await page.click('#association-review-form button[type=submit]');
  await page.waitForSelector('#association-review-open');
  if(writes!==1)throw Error('Review was submitted more than once');
  let shared=await page.evaluate(()=>fetch('/api/investigations').then(r=>r.json()));
  if(shared.total!==1)throw Error('Association did not update shared canonical inventory');
  await page.click('#association-review-open');
  await page.waitForSelector('[data-association-review]');
  if(!(await page.locator('#action-content').textContent()).includes('identity independently verified: No'))throw Error('Context association acquired verified identity');
  await page.locator('[data-association-review]').first().click();
  await page.waitForSelector('#association-review-form');
  const update=spawnSync('python',['tests/ui/seed_investigations.py',directory,'update'],{encoding:'utf8',env:{...process.env,PYTHONPATH:'src'}});
  if(update.status!==0)throw Error('Independent source revision failed: '+update.stderr);
  await page.selectOption('#association-review-form [name=decision]','reject');
  await page.fill('#association-review-form [name=reviewer]','Offline browser reviewer');
  await page.fill('#association-review-form [name=reason]','Reject after checking current evidence.');
  await page.check('#association-review-form [name=confirmed]');
  await page.click('#association-review-form button[type=submit]');
  await page.waitForFunction(()=>document.querySelector('#association-review-result').textContent.includes('changed'));
  if(!(await page.locator('#association-review-form button[type=submit]').isDisabled()))throw Error('Failed preview can be blindly resubmitted');
  await page.click('#association-review-reload');
  await page.waitForSelector('#association-review-form');
  if(await page.isChecked('#association-review-form [name=confirmed]'))throw Error('Preview refresh inherited confirmation');
  await page.selectOption('#association-review-form [name=decision]','reject');
  await page.fill('#association-review-form [name=reviewer]','Offline browser reviewer');
  await page.fill('#association-review-form [name=reason]','Revised evidence reviewed; retain separate investigations.');
  await page.check('#association-review-form [name=confirmed]');
  await page.click('#association-review-form button[type=submit]');
  await page.waitForSelector('#association-review-open');
  shared=await page.evaluate(()=>fetch('/api/investigations').then(r=>r.json()));
  const graph=await page.evaluate(()=>fetch('/api/investigation-graph').then(r=>r.json()));
  if(shared.total!==2||graph.roots.length!==2)throw Error('Rejection did not restore separate shared views');
  if(shared.rows.some(row=>row.assessment.identity_independently_verified||row.assessment.commercial_authority_granted))throw Error('Review granted factual or commercial authority');
  if(errors.length)throw Error(errors.join('; '));
  console.log('Native association review: preview, confirmation, stale-source rejection, reassessment, canonical graph agreement and late-dialog safety PASS');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
